def get_account_text(user_info, user_id, now):
    """تولید متن حساب من با اطلاعات واقعی"""
    username = user_info.get('username')
    username_text = f"@{username}" if username else "ندارد"

    first_name = user_info.get('first_name') or ''
    last_name = user_info.get('last_name') or ''
    full_name = f"{first_name} {last_name}".strip() or "کاربر عزیز"

    active_package = user_info.get('active_package') or '0'
    if active_package == '0':
        active_package = "ندارد"

    expire_date = user_info.get('package_expire_date') or '-'

    return (
        f"👤 حساب من\n"
        f"🆔 شناسه سیستمی شما: {user_id}\n"
        f"🆔 آی دی: {username_text}\n"
        f"👤 نام: {full_name}\n"
        f"📚 سوالات باقی مانده: {user_info.get('questions_remaining', 0)}\n"
        f"📅 سوالات استفاده شده: {user_info.get('questions_used', 0)}\n"
        f"💰 موجودی کیف پول: {user_info.get('wallet', 0):,} ريال\n"
        f"🎁 پکیج فعال: {active_package}\n"
        f"⏳ اعتبار تا: {expire_date}\n"
        f"👤 تعداد زیرمجموعه: {user_info.get('referrals', 0)}\n"
        f"⏳ زمان استعلام: {now}"
    )